#!/usr/bin/env python3
# Write src/audio/birdlib.ts from library.json (build_lib.py): the real calls, numbers only.
import json, os, sys
here = os.path.dirname(__file__); L = json.load(open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, 'library.json')))
ar = lambda v: '[' + ','.join(str(int(x)) if float(x) == int(x) else str(x) for x in v) + ']'
lines = ['// GENERATED by scripts/birds/gen_lib_ts.py from scripts/birds/library.json (build_lib.py, library.py, harvest.py): REAL calls measured on many recordings, numbers only (design/birds.md).',
         '// Each voice is one recording (one bird, or a few): its own spectrum (third octaves, 125 Hz up, dB below its loudest tonal band: H harmonics, N noise) and several calls it made,',
         '// each [length s, apex 0..1, roughness dB, 12 pitch points Hz, 12 loudness points dB]. No recording, nor any part of one, is in the source.', '',
         "export type LibKind = 'gullMew' | 'gullNote' | 'gullAlarm' | 'gullFlight' | 'gullChoke' | 'gullThin' | 'rookCaw' | 'sparrowChirp' | 'blackbirdTink' | 'buzzardMew' | 'owlScreech' | 'gullBeg' | 'albatrossWhirr';",
         'export interface LibVoice { H: number[]; N: number[]; calls: number[][] }', '', 'export const LIB: Record<LibKind, LibVoice[]> = {']
for kind, v in L.items():
    lines.append(f'  {kind}: [')
    for vo in v['voices']:
        lines.append(f"    {{ H: {ar(vo['H'])}, N: {ar(vo['N'])}, calls: [")
        for c in vo['calls']: lines.append('      ' + ar([c['dur'], c['apex'], c['hnr']] + c['f0'] + c['env'] + c.get('bright', [0, 0, 0]) + (c['am'] if c.get('am') else [])) + ',')
        lines.append('    ] },')
    lines.append('  ],')
lines += ['};', '']
open(os.path.join(here, '../../src/audio/birdlib.ts'), 'w').write('\n'.join(lines)); print('wrote birdlib.ts', sum(len(l) for l in lines), 'bytes')
